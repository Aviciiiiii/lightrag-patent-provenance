def main():
    global LANG, OUT_DIR
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--lang', choices=['en', 'zh'], default='en')
    ap.add_argument('--out-dir', type=Path, help='default: results/key_evidence/ for en, local/zh/key_evidence/ for zh')
    a = ap.parse_args()
    LANG = a.lang
    OUT_DIR = a.out_dir or (REPO / 'local/zh/key_evidence' if LANG == 'zh' else None)
    s = q11_side_by_side()
    q06_budget(); api191(); same_cross(); ablation(); f01()
    print(json.dumps(s, ensure_ascii=False))


if __name__ == '__main__':
    main()
