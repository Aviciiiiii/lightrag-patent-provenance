def rel_desc(content: str, src: str) -> list[str]:
    return [l.split('<|#|>')[-1] for l in content.splitlines() if l.startswith('relation<|#|>') and src in l]


def same_cross():
    rows = []
    for cond in ['SAME', 'CROSS']:
        for rep in [1, 2, 3]:
            descs = []
            for c in [0, 1]:
                descs += rel_desc(j(E2 / f'results/chunk_{cond}_r{rep}_c{c}.json')['response']['content'], 'Registration Module')
            rows.append(f"| {cond} r{rep} | {'<br>'.join(descs) or L('（无 Registration Module 关系）', '(no Registration Module relation)')} |")
    md = L("""# 人为切块对照：同一段 Claims 26–28，两种边界

来源：`results/chunk_{SAME,CROSS}_r{1,2,3}_c{0,1}.json`（模型原始抽取输出）。只列出以 Registration Module 为端点的关系描述。CROSS 的边界落在 Claim 27 句中、“machine readable descriptions”之前。

| 条件 / 重复 | Registration Module 的关系描述（原样） |
|---|---|
""", """# Artificial chunking control: the same Claims 26–28, two boundaries

Source: `results/chunk_{SAME,CROSS}_r{1,2,3}_c{0,1}.json` (raw extraction output of the model). Only relation descriptions with Registration Module as an endpoint are listed. In CROSS the boundary falls inside the Claim 27 sentence, before “machine readable descriptions”.

| condition / repeat | relation descriptions of Registration Module (verbatim) |
|---|---|
""") + '\n'.join(rows) + '\n'
    write(E2, 'same_vs_cross.md', md)


def ablation():
    names = {'A': L('原始上下文', 'original context'), 'B': L('+来源字段', '+source fields'),
             'C': L('+来源字段+Claim 原文', '+source fields + claim text')}
    rows = []
    for cond in 'ABC':
        for rep in [1, 2, 3]:
            content = j(E2 / f'results/ablation_{cond}_r{rep}.json')['response']['content']
            rows.append(f"| {names[cond]} r{rep} | {first(content, 160)} | {', '.join(f'[{a}] {b}' for a, b in refs_in_answer(content))} |")
    md = L("""# 来源字段消融（冻结 Q11 / API 392 的检索上下文，只改呈现方式）

条件名对照：dot 原名 A = 原始上下文，B = +来源字段（为 82 条关系追加 publication_numbers、file_path、source_id），C = B + US7991757B2 的 Claim 1/27 原文。引用表三种条件都保持原样（[1] 仍是 US10867122B1.txt）。来源：`results/ablation_{A,B,C}_r{1,2,3}.json`。

| 条件 | 回答开头 | 回答末尾引用 |
|---|---|---|
""", """# Source-field ablation (Q11's retrieved context from API 392 frozen; only its presentation changes)

Condition names: dot's A = original context; B = +source fields (`publication_numbers`, `file_path`, `source_id` added to the 82 relations); C = B + the original text of US7991757B2 claims 1 and 27. The reference list is kept unchanged in all three (`[1]` is still US10867122B1.txt). Source: `results/ablation_{A,B,C}_r{1,2,3}.json`.

| condition | start of answer | references at the end |
|---|---|---|
""") + '\n'.join(rows) + '\n'
    write(E2, 'ablation_source_fields.md', md)


def f01_edges(run: str, base: Path = E3 / 'results') -> list[str]:
    out = []
    for r in j(base / run / 'parsed_extraction.json')['records']:
        for e in r['edges']:
            for x in e['records']:
                d = x['description']
                if 'ntology' in d and ('case' in d.lower() or 'expert' in d.lower() or 'Unified Medical' in d):
                    out.append(f"{x['src_id']} → {x['tgt_id']}: {d}")
    return out


