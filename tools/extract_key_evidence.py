"""Extract the key evidence snippets quoted in the READMEs, straight from saved files. No API calls.

    python tools/extract_key_evidence.py                 # English, into experiments/0X_*/results/key_evidence/
    python tools/extract_key_evidence.py --lang zh       # Chinese, into local/zh/key_evidence/ (not committed)
    python tools/extract_key_evidence.py --lang zh --out-dir <dir>

Inputs are the committed results of the original run only.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
E1 = REPO / 'experiments/01_baseline_index_qa'
E2 = REPO / 'experiments/02_provenance_ablation_and_chunk_control'
E3 = REPO / 'experiments/03_chunk_boundary_full_pipeline'
TARGET = 'US7991757B2'
LANG = 'en'
OUT_DIR: Path | None = None  # None: public English location next to the results


def L(zh: str, en: str) -> str:
    return zh if LANG == 'zh' else en


def write(exp_dir: Path, name: str, text: str):
    out = (OUT_DIR / exp_dir.name if OUT_DIR else exp_dir / 'results/key_evidence') / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')


def j(p):
    return json.loads(Path(p).read_text())


def rel(p: Path) -> str:
    return str(p.relative_to(REPO))


def answer(res: dict) -> str:
    return ((res.get('result') or {}).get('llm_response') or {}).get('content') or ''


def refs_in_answer(text: str) -> list[str]:
    tail = text.split('### References')[-1] if '### References' in text else ''
    return re.findall(r'\[(\d+)\]\s*([\w.]+)', tail)


def first(text: str, n=420) -> str:
    t = ' '.join(text.split())
    return t[:n] + ('…' if len(t) > n else '')


def kg_lines(prompt: str, name: str) -> list[str]:
    return [l for l in prompt.splitlines() if l.startswith('{"entity') and f'"{name}"' in l]


def q11_side_by_side() -> dict:
    res = j(E1 / 'results/supplement_budget_Q11_supplementary_mix.json')
    data = res['result']['data']
    req = j(E1 / 'results/key_logs/api_0392_request.json')
    sys_prompt, user = req['messages'][0]['content'], req['messages'][1]['content']
    ent = next(e for e in data['entities'] if e['entity_name'] == 'Registration Module')
    rel_rec = next(r for r in data['relationships'] if {'Registration Module', 'External Recommender'} == {r['src_id'], r['tgt_id']})
    ref_block = sys_prompt[sys_prompt.find('Reference Document List (Each'):]
    ref_block = ref_block[ref_block.find('```') + 3:]
    ref_block = ref_block[:ref_block.find('```')].strip()
    ans = j(E1 / 'results/key_logs/api_0392_response.json')['content']
    stats = {
        'entities_in_result': len(data['entities']),
        'target_entities': [e['entity_name'] for e in data['entities'] if TARGET in (e.get('file_path') or '')],
        'target_relations': sum(1 for r in data['relationships'] if TARGET in (r.get('file_path') or '')),
        'target_chunks': sum(1 for c in data['chunks'] if TARGET in c.get('file_path', '')),
        'prompt_chars': len(sys_prompt), 'prompt_target_mentions': sys_prompt.count(TARGET),
        'prompt_file_path': sys_prompt.count('file_path'), 'prompt_source_id': sys_prompt.count('source_id'),
    }
    kl = kg_lines(sys_prompt, 'Registration Module')
    second = kl[1] if len(kl) > 1 else L('（见原文件）', '(see file)')
    src1, src2 = rel(E1 / 'results/supplement_budget_Q11_supplementary_mix.json'), rel(E1 / 'results/key_logs/api_0392_request.json')
    md = L(f"""# Q11（扩展预算，mix）：同一次调用里，结构化返回 vs 送给模型的提示

来源：`{src1}`（`aquery_llm` 同一次调用的结构化返回，API 调用 391–392）与 `{src2}`（实际发给模型的请求）。由 `tools/extract_key_evidence.py --lang zh` 生成。

问题（user 消息）：{user}

## 同一个实体 / 同一条关系

| | 结构化返回 `result.data`（带来源） | 发给模型的提示（API 392 system prompt） |
|---|---|---|
""", f"""# Q11 (extended budget, mix): structured result vs. the prompt sent to the model, same call

Sources: `{src1}` (structured result of the same `aquery_llm` call, API calls 391–392) and `{src2}` (the request actually sent to the model). Generated by `tools/extract_key_evidence.py`.

Question (user message): {user}

## The same entity / the same relation

| | structured result `result.data` (with source) | prompt sent to the model (API 392 system prompt) |
|---|---|---|
""")
    md += (f"| {L('实体', 'entity')} Registration Module | `file_path`: `{ent['file_path']}`<br>`source_id`: `{ent['source_id']}` | `{kl[0][:260]}…` |\n"
           f"| {L('关系', 'relation')} External Recommender — Registration Module | `file_path`: `{rel_rec['file_path']}`<br>`source_id`: `{rel_rec['source_id']}` | `{second[:260]}…` |\n\n")
    ents = ', '.join(stats['target_entities'])
    md += L(f"""## 计数

- 结构化返回中来自 {TARGET} 的实体：{len(stats['target_entities'])} 个（{ents}）；关系：{stats['target_relations']} 条；原文 chunk：**{stats['target_chunks']}** 个。
- 发给模型的 system prompt 共 {stats['prompt_chars']:,} 字符，其中 `{TARGET}` 出现 **{stats['prompt_target_mentions']}** 次，`file_path` 出现 {stats['prompt_file_path']} 次，`source_id` 出现 {stats['prompt_source_id']} 次。
- 提示里的 Reference Document List（只由 chunk 生成）：
""", f"""## Counts

- Structured result, from {TARGET}: {len(stats['target_entities'])} entities ({ents}), {stats['target_relations']} relations, **{stats['target_chunks']}** text chunks.
- The system prompt sent to the model has {stats['prompt_chars']:,} characters; `{TARGET}` appears **{stats['prompt_target_mentions']}** times, `file_path` {stats['prompt_file_path']} times, `source_id` {stats['prompt_source_id']} times.
- Reference Document List in the prompt (built from chunks only):
""")
    md += f"""
```
{ref_block}
```

## {L('模型回答（API 392 响应，节选）', 'Model answer (API 392 response, excerpt)')}

> {first(ans, 700)}

{L('回答末尾引用：', 'References at the end of the answer: ')}{', '.join(f'[{a}] {b}' for a, b in refs_in_answer(ans))}
"""
    write(E1, 'q11_api392_side_by_side.md', md)
    return stats


def q06_budget():
    base, sup = j(E1 / 'results/full_Q06_mix.json'), j(E1 / 'results/supplement_budget_Q06_mix.json')
    probe = j(E1 / 'evidence/retrieval_rank_probe.json')
    ranks = {r['question_id']: [(x['rank'], x['id']) for x in r['ranked'] if TARGET in x['id']] for r in probe['rows']}
    nb = sum(1 for c in base['result']['data']['chunks'] if TARGET in c['file_path'])
    ns = sum(1 for c in sup['result']['data']['chunks'] if TARGET in c['file_path'])
    md = L(f"""# Q06（跨文档比较）：基线预算 vs 扩展预算

| | 基线 `full_Q06_mix.json` | 扩展预算 `supplement_budget_Q06_mix.json` |
|---|---|---|
| 参数 | top_k=12, chunk_top_k=8, 实体/关系 2000/2000, 总 8000 | top_k=40, chunk_top_k=20, 实体/关系 6000/8000, 总 30000（源码默认量级） |
| 上下文 chunk 来自 {TARGET} | {nb} | {ns} |
""", f"""# Q06 (cross-document comparison): baseline budget vs. extended budget

| | baseline `full_Q06_mix.json` | extended budget `supplement_budget_Q06_mix.json` |
|---|---|---|
| parameters | top_k=12, chunk_top_k=8, entity/relation 2000/2000, total 8000 | top_k=40, chunk_top_k=20, entity/relation 6000/8000, total 30000 (the order of LightRAG's defaults) |
| context chunks from {TARGET} | {nb} | {ns} |
""")
    md += f"| {L('回答开头', 'start of answer')} | {first(answer(base), 220)} | {first(answer(sup), 220)} |\n\n"
    md += L(f"同一 Embedding 下 {TARGET} 两个 chunk 的向量排名（`evidence/retrieval_rank_probe.json`）：Q06 {ranks.get('Q06')}；Q11 {ranks.get('Q11_supplementary')}。基线 chunk_top_k=8，扩展 20。\n",
            f"Vector ranks of the two {TARGET} chunks under the same embedding (`evidence/retrieval_rank_probe.json`): Q06 {ranks.get('Q06')}; Q11 {ranks.get('Q11_supplementary')}. Baseline chunk_top_k=8, extended 20.\n")
    write(E1, 'q06_budget.md', md)


