"""Build the phenomenon × run table for docs/REPRODUCIBILITY.md from saved files. No API calls.

Inputs per run: docs/scoring/scores_<label>.json (tools/score_runs.py), the cost ledgers, full_graph.json,
and the request log of the extended-budget Q11 mix call (local runs/ logs, or the committed key log).

    python tools/build_reproducibility.py                       # all runs found, print tables
    python tools/build_reproducibility.py --write docs/REPRODUCIBILITY.md
    python tools/build_reproducibility.py --lang zh --write local/zh/REPRODUCIBILITY.md
    python tools/build_reproducibility.py original 20261105 20261115 20261201 --write docs/REPRODUCIBILITY.md

Labels default to "original" plus every date that has both experiments/01_*/results_rerun_<label>/ and
docs/scoring/scores_<label>.json. The request log of a rerun is looked up automatically in
runs/01_baseline_index_qa/rerun_<label>/logs and runs/rerun_01_baseline_index_qa_<label>T*/logs
(--extra-logs adds more directories). --write replaces only the part of the file between the
BEGIN/END markers below; the narrative around the tables is written separately and must be updated by hand.
"""
from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS = REPO / 'runs'
EXPS = ['01_baseline_index_qa', '02_provenance_ablation_and_chunk_control', '03_chunk_boundary_full_pipeline']
SEP = '<SEP>'
TARGET = 'US7991757B2'
LANG = 'en'


def L(zh: str, en: str) -> str:
    return zh if LANG == 'zh' else en


def j(p):
    return json.loads(Path(p).read_text())


def res_dir(exp, label):
    base = REPO / 'experiments' / exp
    return base / 'results' if label == 'original' else base / f'results_rerun_{label}' / 'results'


BEGIN = '<!-- BEGIN tables generated by tools/build_reproducibility.py -->'
END = '<!-- END tables generated by tools/build_reproducibility.py -->'


def log_dirs(label):
    if label == 'original':
        return [REPO / 'experiments/01_baseline_index_qa/results/key_logs', RUNS / '01_baseline_index_qa/original/logs']
    return [RUNS / f'01_baseline_index_qa/rerun_{label}/logs'] + sorted(RUNS.glob(f'rerun_01_baseline_index_qa_{label}T*/logs'))


def default_labels():
    found = sorted(d.name.removeprefix('results_rerun_') for d in (REPO / 'experiments' / EXPS[0]).glob('results_rerun_*')
                   if (REPO / f'docs/scoring/scores_{d.name.removeprefix("results_rerun_")}.json').exists())
    return ['original'] + found


def find_request(label, call_id, extra_logs):
    cands = log_dirs(label) + extra_logs
    for d in cands:
        f = Path(d) / f'api_{call_id:04d}_request.json'
        if f.exists():
            return j(f)
    return None


def structural(label, extra_logs):
    r1 = res_dir(EXPS[0], label)
    sup = j(r1 / 'supplement_budget_Q11_supplementary_mix.json')
    req = find_request(label, sup['api_call_id_range'][-1], extra_logs)
    d = sup['result']['data']
    if req:
        sp = req['messages'][0]['content']
        lines = [l for l in sp.splitlines() if l.startswith('{"entity')]
        nf = sum('file_path' in l for l in lines)
        sf = f"{sum(bool(e.get('file_path')) for e in d['entities'] + d['relationships'])}/{len(d['entities']) + len(d['relationships'])}"
        p1 = L(f"提示中实体/关系行 {len(lines)} 条，含 `file_path` {nf} 条；结构化返回含 `file_path` {sf}",
               f"{len(lines)} entity/relation lines in the prompt, {nf} with `file_path`; structured result with `file_path` {sf}")
    else:
        p1 = L('（无请求日志）', '(no request log)')
    g = j(r1 / 'full_graph.json')
    multi = 0
    for n in g['nodes']:
        pubs = {p.removesuffix('.txt') for p in (n.get('file_path') or '').split(SEP) if p}
        multi += len(pubs) >= 2
    claims = sum(bool(re.search(r'\bclaim\s*\d+\b', str(n.get('id', '')), re.I)) for n in g['nodes'])
    ne, nc = sum(TARGET in (e.get('file_path') or '') for e in d['entities']), sum(TARGET in c['file_path'] for c in d['chunks'])
    tgt = L(f"{ne} 个实体、{nc} 个 chunk", f"{ne} entities, {nc} chunks")
    return {'P1': p1, 'P1_q11_target': tgt, 'P6': f"{multi}/{len(g['nodes'])} ({len(g['edges'])} {L('边', 'edges')})", 'P7': f'{claims}'}


def ledger(label):
    out = {}
    for exp in EXPS:
        f = res_dir(exp, label) / 'cost_ledger.json'
        if f.exists():
            d = j(f)
            k = Counter(c['kind'] for c in d['calls'])
            out[exp[:2]] = {'llm': k.get('llm', 0), 'embedding': k.get('embedding', 0),
                            'cny': d['estimated_observed_cost_cny'] + d['reserved_unknown_cny'],
                            'length': sum(c.get('finish_reason') == 'length' for c in d['calls'])}
    return out


def scores(label):
    rows = j(REPO / f'docs/scoring/scores_{label}.json')['rows']
    return {(r['rubric'], r['item']): r['value'] for r in rows}


def frac(s, code, items):
    vals = [s.get((code, i)) for i in items]
    vals = [v for v in vals if v is not None]
    return f'{sum(vals)}/{len(vals)}' if vals else '—'


def yn(v):
    return {True: L('是', 'yes'), False: L('否', 'no'), None: '—'}[v]


def behavioural(label):
    s = scores(label)
    q = [f'Q{i:02d}' for i in range(1, 11)]
    abc = lambda code: ' / '.join(frac(s, code, [f'{c}{r}' for r in (1, 2, 3)]) for c in 'ABC')  # noqa: E731
    rows = {
        L('S1 naive 完成核心任务（Q01–Q10）', 'S1 naive completes the core task (Q01–Q10)'): frac(s, 'S1', [f'{x}/naive' for x in q]),
        L('S1 mix 完成核心任务（Q01–Q10）', 'S1 mix completes the core task (Q01–Q10)'): frac(s, 'S1', [f'{x}/mix' for x in q]),
        L('S1 Q06 基线 naive / mix 完成', 'S1 Q06 baseline naive / mix completed'): f"{yn(s.get(('S1', 'Q06/naive')))} / {yn(s.get(('S1', 'Q06/mix')))}",
        L('S2 Q06 基线上下文含两篇所需原文（naive / mix）', 'S2 Q06 baseline context contains both required texts (naive / mix)'): f"{yn(s.get(('S2', 'Q06/naive')))} / {yn(s.get(('S2', 'Q06/mix')))}",
        L('S1 扩展预算 Q06 naive / mix 完成', 'S1 extended-budget Q06 naive / mix completed'): f"{yn(s.get(('S1', 'supplement/Q06/naive')))} / {yn(s.get(('S1', 'supplement/Q06/mix')))}",
        L('S1 扩展预算 Q11 naive / mix 完成', 'S1 extended-budget Q11 naive / mix completed'): f"{yn(s.get(('S1', 'supplement/Q11/naive')))} / {yn(s.get(('S1', 'supplement/Q11/mix')))}",
        L('S3 肯定性错误归属（实验 01 全部 26 个回答）', 'S3 affirmative misattribution (all 26 answers of experiment 01)'): frac(s, 'S3', [k[1] for k in s if k[0] == 'S3']),
        L('S5 消融：认对专利（原始上下文 / +来源 / +来源+原文）', 'S5 ablation: right patent (original context / +sources / +sources+text)'): abc('S5'),
        L('S6 消融：有证据地完成 Claim 任务', 'S6 ablation: claim task completed with evidence'): abc('S6'),
        L('S7 消融：引用编号冲突', 'S7 ablation: citation-number conflict'): abc('S7'),
        L('S4 消融：肯定性错误归属（9 次）', 'S4 ablation: affirmative misattribution (9 answers)'): frac(s, 'S4', [f'{c}{r}' for c in 'ABC' for r in (1, 2, 3)]),
        L('S8 人为切块：完整关系保留（同块 / 句内切分）', 'S8 artificial chunking: complete relation kept (same chunk / mid-sentence split)'): ' / '.join(frac(s, 'S8', [f'{c}_r{r}' for r in (1, 2, 3)]) for c in ('SAME', 'CROSS')),
    }
    for g in ('F01', 'F05', 'F04'):
        rows[L(f'S9 {g} 目标谓词进入合并图（同块 / 跨块）', f'S9 {g} target predicates in the merged graph (same-chunk / cross-chunk)')] = ' / '.join(frac(s, 'S9', [f'{g}_{c}_r{r}' for r in (1, 2, 3)]) for c in 'AB')
    rows[L('S10 实验 03 有截断的 run', 'S10 experiment-03 runs with truncation')] = ', '.join(k[1] for k, v in s.items() if k[0] == 'S10' and v) or L('无', 'none')
    clean = []
    for r in (1, 2, 3):
        a, b = f'F01_A_r{r}', f'F01_B_r{r}'
        if s.get(('S10', a)) is False and s.get(('S10', b)) is False:
            clean.append(f"r{r}: {L('同块', 'same')}{'✓' if s.get(('S9', a)) else '✗'} {L('跨块', 'cross')}{'✓' if s.get(('S9', b)) else '✗'}")
    rows[L('F01 干净配对（双方都无截断）', 'F01 clean pairs (no truncation on either side)')] = '; '.join(clean) or L('无', 'none')
    runs3 = [f'{g}_{c}_r{r}' for g in ('F01', 'F05', 'F04') for c in 'AB' for r in (1, 2, 3)]
    rows[L('S11 mix 取回全部目标原文', 'S11 mix retrieves all target text')] = frac(s, 'S11', runs3)
    for kind in ('mix', 'naive', 'forced'):
        rows[L(f'S12 {kind} 核心正确', f'S12 {kind} core answer correct')] = frac(s, 'S12', [f'{x}/{kind}' for x in runs3])
    rows[L('S13 naive 写错 Claim 依赖', 'S13 naive states a wrong claim dependency')] = ', '.join(k[1] for k, v in s.items() if k[0] == 'S13' and v) or L('无', 'none')
    return rows


def tables(labels, extra_logs):
    st = {l: structural(l, extra_logs) for l in labels}
    be = {l: behavioural(l) for l in labels}
    lg = {l: ledger(l) for l in labels}
    head = L('| 现象 | ', '| phenomenon | ') + ' | '.join(labels) + ' |\n|---|' + '---|' * len(labels)
    out = [L('### 结构性', '### Structural'), '', head]
    for k, name in (('P1', L('P1 扩展预算 Q11 mix：提示中的来源字段', 'P1 extended-budget Q11 mix: source fields in the prompt')),
                    ('P1_q11_target', L('Q11 结构化返回中来自 US7991757B2 的', 'Q11 structured result, items from US7991757B2')),
                    ('P6', L('P6 多源节点 / 总节点', 'P6 multi-source nodes / all nodes')), ('P7', L('P7 图中的 Claim 实体数', 'P7 claim entities in the graph'))):
        out.append(f'| {name} | ' + ' | '.join(st[l][k] for l in labels) + ' |')
    out += ['', L('### 行为性（评分：docs/SCORING_RUBRIC.md）', '### Behavioural (scored with docs/SCORING_RUBRIC.md)'), '', head]
    for k in be[labels[0]]:
        out.append(f'| {k} | ' + ' | '.join(be[l][k] for l in labels) + ' |')
    out += ['', L('### 调用与费用（账本估算，非账单；不计缓存优惠）', '### Calls and cost (ledger estimate, not an invoice; cache discounts not counted)'), '',
            L('| 实验 | ', '| experiment | ') + ' | '.join(labels) + ' |\n|---|' + '---|' * len(labels)]
    for e in ('01', '02', '03'):
        cells = []
        for l in labels:
            x = lg[l].get(e)
            cells.append(L(f"{x['llm']} LLM + {x['embedding']} Emb，¥{x['cny']:.2f}，截断 {x['length']}", f"{x['llm']} LLM + {x['embedding']} emb, CNY {x['cny']:.2f}, truncated {x['length']}") if x else '—')
        out.append(f'| {e} | ' + ' | '.join(cells) + ' |')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('labels', nargs='*', help='default: original + every scored rerun')
    ap.add_argument('--extra-logs', nargs='*', default=[], help='additional log dirs searched for every label')
    ap.add_argument('--write', type=Path, help='replace the marked block in this Markdown file')
    ap.add_argument('--lang', choices=['en', 'zh'], default='en')
    a = ap.parse_args()
    global LANG
    LANG = a.lang
    labels = a.labels or default_labels()
    md = tables(labels, [Path(x) for x in a.extra_logs])
    if a.write:
        text = a.write.read_text(encoding='utf-8')
        if BEGIN not in text or END not in text:
            raise SystemExit(f'markers not found in {a.write}')
        i, k = text.index(BEGIN) + len(BEGIN), text.index(END)
        a.write.write_text(text[:i] + '\n\n' + md + '\n' + text[k:], encoding='utf-8')
        print(f'wrote tables for {", ".join(labels)} into {a.write}')
    else:
        print(md)


if __name__ == '__main__':
    main()
